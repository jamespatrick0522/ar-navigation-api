import 'reflect-metadata';
import 'dotenv/config';
import {strict as assert} from 'node:assert';
import {test} from 'node:test';
import {Client} from 'pg';
import {drizzle} from 'drizzle-orm/node-postgres';
import {plainToInstance} from 'class-transformer';
import {validate} from 'class-validator';
import {ArNavigationRoutesService} from '../src/modules/ar-navigation-routes/ar-navigation-routes.service';
import {SaveArNavigationRouteDto} from '../src/modules/ar-navigation-routes/dto/save-ar-navigation-route.dto';

const payload = (): SaveArNavigationRouteDto => ({
  startAnchorCode: 'MAIN_ENTRANCE',
  coordinateFrame: 'marker-floor-v2',
  markerFloorOffsetMeters: 1.2,
  title: 'Registrar verified route',
  points: [
    {pointOrder: 0, pointType: 'entrance', label: 'Entrance', x: 0, y: 0, z: 0},
    {pointOrder: 1, pointType: 'turn', label: 'Turn 1', x: 0, y: 0, z: 3},
    {pointOrder: 2, pointType: 'destination', label: 'Registrar', x: 4, y: 0, z: 3},
  ],
});

test('upload DTO requires coordinate metadata and complete route points', async () => {
  assert.equal((await validate(plainToInstance(SaveArNavigationRouteDto, payload()))).length, 0);
  assert.ok((await validate(plainToInstance(SaveArNavigationRouteDto, {}))).length > 0);
  const incomplete = {...payload(), points: []};
  assert.ok((await validate(plainToInstance(SaveArNavigationRouteDto, incomplete))).length > 0);
});

test('route invariants reject unsafe calibration before touching storage', async () => {
  const service = new ArNavigationRoutesService({transaction: () => assert.fail('Invalid route touched storage')});
  await assert.rejects(service.saveRoomRoute(1, {...payload(), coordinateFrame: 'legacy-v1'}));
  await assert.rejects(service.saveRoomRoute(1, {...payload(), markerFloorOffsetMeters: NaN}));
  const duplicate = payload();
  duplicate.points[1].pointOrder = 0;
  await assert.rejects(service.saveRoomRoute(1, duplicate));
  const invalid = payload();
  invalid.points[2].x = Infinity;
  await assert.rejects(service.saveRoomRoute(1, invalid));
  const stair = payload();
  stair.points[1].pointType = 'stair-start';
  stair.points[1].direction = 'up';
  await assert.rejects(service.saveRoomRoute(1, stair));
});

test('Postgres route save, independent readback, and failed replacement rollback', {skip: !process.env.DATABASE_URL}, async () => {
  const url = new URL(process.env.DATABASE_URL!);
  // Session-local tests must bypass transaction poolers, which can retain temporary tables.
  if (url.hostname.endsWith('.neon.tech')) url.hostname = url.hostname.replace('-pooler.', '.');
  const client = new Client({connectionString: url.toString(), application_name: 'school-ar-route-regression', connectionTimeoutMillis: 15000});
  await client.connect();
  try {
    // Session-local tables shadow the real tables. These tests never modify school records.
    await client.query(`
      CREATE TEMP TABLE rooms (id integer PRIMARY KEY, room_name text, room_code text, is_active boolean DEFAULT true);
      CREATE TEMP TABLE navigation_anchors (id integer PRIMARY KEY, code text UNIQUE, name text, is_active boolean DEFAULT true);
      CREATE TEMP TABLE ar_navigation_routes (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        room_id integer NOT NULL, start_anchor_id integer NOT NULL, title varchar(180) NOT NULL,
        description text, coordinate_frame varchar(40) NOT NULL DEFAULT 'legacy-v1',
        marker_floor_offset_meters double precision NOT NULL DEFAULT 0, is_active boolean NOT NULL DEFAULT true,
        created_at timestamp DEFAULT now(), updated_at timestamp DEFAULT now(), UNIQUE(room_id, start_anchor_id)
      );
      CREATE TEMP TABLE ar_navigation_route_points (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, route_id integer NOT NULL, point_order integer NOT NULL,
        point_type varchar(40) NOT NULL, label varchar(160), direction varchar(40),
        x double precision NOT NULL CHECK (x <> -999), y double precision NOT NULL, z double precision NOT NULL,
        created_at timestamp DEFAULT now(), updated_at timestamp DEFAULT now(), UNIQUE(route_id, point_order)
      );
      INSERT INTO rooms VALUES (1, 'Registrar', 'REGISTRAR', true);
      INSERT INTO navigation_anchors VALUES (1, 'MAIN_ENTRANCE', 'Main Entrance', true);
    `);
    const db = drizzle(client);
    const adminService = new ArNavigationRoutesService(db);
    const guestService = new ArNavigationRoutesService(db);
    const saved = await adminService.saveRoomRoute(1, payload());
    const loaded = await guestService.getRoomRoute(1, 'PAC-NAV-START-MAIN-ENTRANCE');
    assert.deepEqual(loaded, saved);
    assert.equal(loaded.markerFloorOffsetMeters, 1.2);
    assert.equal(loaded.points.length, 3);
    assert.equal((await guestService.getRouteSummaries('PAC-NAV-START-MAIN-ENTRANCE')).length, 1);

    const failure = payload();
    failure.title = 'Should not replace the saved route';
    failure.points[2].x = -999;
    await assert.rejects(adminService.saveRoomRoute(1, failure));
    assert.deepEqual(await guestService.getRoomRoute(1), saved);

    const changed = payload();
    changed.points[2].x = 6;
    const replacement = await adminService.saveRoomRoute(1, changed);
    assert.equal(replacement.id, saved.id);
    assert.equal(replacement.points.length, 3);
    assert.equal(replacement.points[2].x, 6);
    await client.query('DELETE FROM navigation_anchors');
    await assert.rejects(adminService.saveRoomRoute(1, payload()), /Start anchor not found/);
  } finally {
    try {
      await client.query('DROP TABLE IF EXISTS pg_temp.ar_navigation_route_points, pg_temp.ar_navigation_routes, pg_temp.navigation_anchors, pg_temp.rooms');
    } finally {
      await client.end();
    }
  }
});
