import 'dotenv/config';
import {strict as assert} from 'node:assert';
import {test} from 'node:test';
import {Client} from 'pg';
import {drizzle} from 'drizzle-orm/node-postgres';
import {driveImageId, formatPersonName, groupMediaRows, importRoomMedia, MediaSourceRow, samePerson} from '../src/scripts/seed-minot34-media';

const row = (overrides: Partial<MediaSourceRow> = {}): MediaSourceRow => ({
  sourceRow: 2, sourceRoom: 'Test A', roomCode: 'TEST-A', personName: 'GLADYS PIELAGO',
  roomImageSourceUrl: 'https://drive.google.com/file/d/photo-A/view?usp=drive_link', personImageSourceUrl: null, ...overrides,
});

test('media source validation and person matching preserve complete existing names', () => {
  assert.equal(driveImageId(row().roomImageSourceUrl!), 'photo-A');
  assert.throws(() => driveImageId('https://example.com/file/d/photo-A/view'));
  assert.equal(formatPersonName('ATTY,JERRY DALAGAN'), 'Atty. Jerry Dalagan');
  assert.equal(formatPersonName('RANDY P.INRES'), 'Randy P. Inres');
  assert.ok(samePerson('Gladys Mae Cuevas Pielago', 'GLADYS PIELAGO'));
  assert.ok(!samePerson('Leodith P. Rodrigo', 'Jaypee Bascal Torrrenfranca'));
  assert.throws(() => groupMediaRows([row({roomCode: null})]), /confirm the room mapping/);
  assert.equal(groupMediaRows([row(), row({sourceRow: 3})]).size, 1);
});

test('media import preserves room identity/location and supports idempotent staff updates with rollback', {skip: !process.env.DATABASE_URL}, async () => {
  const url = new URL(process.env.DATABASE_URL!);
  if (url.hostname.endsWith('.neon.tech')) url.hostname = url.hostname.replace('-pooler.', '.');
  const client = new Client({connectionString: url.toString(), application_name: 'school-ar-room-media-tests', connectionTimeoutMillis: 15000});
  await client.connect();
  try {
    await client.query(`
      CREATE TEMP TABLE rooms (LIKE public.rooms INCLUDING DEFAULTS);
      CREATE TEMP TABLE room_people (LIKE public.room_people INCLUDING DEFAULTS);
      CREATE TEMP TABLE room_gallery (LIKE public.room_gallery INCLUDING DEFAULTS);
      CREATE TEMP TABLE buildings (LIKE public.buildings INCLUDING DEFAULTS);
      CREATE TEMP TABLE floors (LIKE public.floors INCLUDING DEFAULTS);
      CREATE TEMP TABLE room_categories (LIKE public.room_categories INCLUDING DEFAULTS);
      ALTER TABLE rooms ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE rooms ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000);
      ALTER TABLE buildings ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE buildings ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000);
      ALTER TABLE floors ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE floors ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000);
      ALTER TABLE room_people ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE room_people ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000);
      ALTER TABLE room_gallery ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE room_gallery ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000);
      INSERT INTO rooms (id,room_code,room_name,category_id,building_id,floor_id) VALUES
        (1,'TEST-A','Test A',3,2,4),(2,'TEST-B','Test B',1,1,1);
      INSERT INTO room_categories (id,code,name) VALUES (3,'ACADEMIC','Academic');
      INSERT INTO room_people (id,room_id,full_name,role_title,is_primary,is_active) VALUES
        (1,1,'Gladys Mae Cuevas Pielago','Head / Instructor',true,true),
        (2,2,'Leodith P. Rodrigo','Head / Instructor',true,true);
    `);
    const db = drizzle(client);
    const imageUrl = (source: string) => `https://example.com/media/room-images/${driveImageId(source)}.jpg`;
    const input = [row(), row({sourceRow: 3, personName: null, roomImageSourceUrl: 'https://drive.google.com/file/d/photo-B/view'}),
      row({sourceRow: 4, roomCode: 'TEST-B', personName: 'JAYPEE BASCAL TORRRENFRANCA'})];
    const first = await importRoomMedia(db, input, imageUrl, 'primary-keep');
    assert.equal(first.roomsUpdated, 2);
    assert.equal(first.galleryImagesAdded, 3);
    assert.equal(first.staffAdded, 1);
    const rooms = (await client.query('SELECT id,room_name,category_id,building_id,floor_id FROM rooms ORDER BY id')).rows;
    assert.deepEqual(rooms[0], {id: 1, room_name: 'Test A', category_id: 3, building_id: 2, floor_id: 4});
    assert.equal((await client.query('SELECT full_name FROM room_people WHERE id=1')).rows[0].full_name, 'Gladys Mae Cuevas Pielago');
    assert.deepEqual((await client.query('SELECT is_primary,is_active FROM room_people WHERE id=2')).rows[0], {is_primary: false, is_active: true});
    const repeat = await importRoomMedia(db, input, imageUrl, 'primary-keep');
    assert.equal(repeat.galleryImagesAdded, 0);
    assert.equal(repeat.staffAdded, 0);
    const count = (await client.query('SELECT count(*) FROM room_people')).rows[0].count;
    await importRoomMedia(db, [row({personName: 'Ignored Name'})], imageUrl, 'images-only');
    assert.equal((await client.query('SELECT count(*) FROM room_people')).rows[0].count, count);
    const oldPhoto = (await client.query('SELECT image_url FROM rooms WHERE id=1')).rows[0].image_url;
    await assert.rejects(importRoomMedia(db, [row({roomImageSourceUrl: 'https://drive.google.com/file/d/new-photo/view'}), row({roomCode: 'MISSING'})], imageUrl, 'images-only'));
    assert.equal((await client.query('SELECT image_url FROM rooms WHERE id=1')).rows[0].image_url, oldPhoto);
    await client.query('UPDATE room_people SET is_primary=true WHERE id=2');
    await importRoomMedia(db, [input[2]], imageUrl, 'primary-replace');
    assert.deepEqual((await client.query('SELECT is_primary,is_active FROM room_people WHERE id=2')).rows[0], {is_primary: false, is_active: false});
    const newRoom = {roomCode: 'TEST-NEW', roomName: 'New School', categoryCode: 'ACADEMIC'};
    const newInput = [row({roomCode: newRoom.roomCode, personName: null})];
    assert.equal((await importRoomMedia(db, newInput, imageUrl, 'images-only', [newRoom])).roomsCreated, 1);
    assert.equal((await importRoomMedia(db, newInput, imageUrl, 'images-only', [newRoom])).roomsCreated, 0);
    assert.equal((await client.query("SELECT f.floor_name FROM rooms r JOIN floors f ON f.id=r.floor_id WHERE r.room_code='TEST-NEW'")).rows[0].floor_name, 'Floor to be confirmed');
  } finally {
    try { await client.query('DROP TABLE IF EXISTS pg_temp.room_gallery, pg_temp.room_people, pg_temp.rooms, pg_temp.room_categories, pg_temp.floors, pg_temp.buildings'); }
    finally { await client.end(); }
  }
});
